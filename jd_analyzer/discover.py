"""Discover company boards from the SimplifyJobs internship list.

No job board lets you search every company, so we borrow a company list:
every Greenhouse, Lever or Ashby link in SimplifyJobs/Summer2027-Internships
(any role, not just PM) names a company board we can then check for PM interns.
We only take board tokens from Simplify; job text always comes from the
job boards' own APIs.

Usage:
    python -m jd_analyzer.discover    # writes data/boards_discovered.txt
"""

import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import parse_qs, unquote, urlparse

import requests

from jd_analyzer.boards import Board, parse_board_line, read_boards, write_boards

ROOT = Path(__file__).resolve().parent.parent
SEED_BOARDS = ROOT / "boards.txt"
OUTPUT = ROOT / "data" / "boards_discovered.txt"
SIMPLIFY_URL = (
    "https://raw.githubusercontent.com/SimplifyJobs/Summer2027-Internships/"
    "dev/.github/scripts/listings.json"
)


def board_from_url(url: str) -> Board | None:
    """Return the Board a job link points at, or None if it isn't one we support.

    Raises ValueError if it is a supported job board but the token is unsafe.
    """
    try:
        u = urlparse(url)
    except ValueError:
        return None
    host = (u.hostname or "").lower()
    # Decode each segment: Ashby links spell "Hippocratic AI" as "Hippocratic%20AI".
    path = [unquote(s) for s in u.path.split("/") if s]

    if host in ("boards.greenhouse.io", "job-boards.greenhouse.io"):
        if path and path[0] == "embed":  # .../embed/job_app?for=<token>
            token = parse_qs(u.query).get("for", [""])[0]
        else:
            token = path[0] if path else ""
        return parse_board_line(f"greenhouse:{token}") if token else None
    if host == "jobs.lever.co" and path:
        return parse_board_line(f"lever:{path[0]}")
    if host == "jobs.ashbyhq.com" and path:
        return parse_board_line(f"ashby:{path[0]}")
    return None


def boards_from_listings(listings: list[dict]) -> tuple[list[Board], list[str]]:
    """Unique boards across all listings, plus the links we refused as unsafe."""
    boards, rejected = [], []
    for listing in listings:
        try:
            board = board_from_url(listing.get("url", ""))
        except ValueError:
            rejected.append(listing.get("url", ""))
            continue
        if board:
            boards.append(board)
    return list(dict.fromkeys(boards)), rejected


def main() -> int:
    print(f"Downloading {SIMPLIFY_URL}")
    resp = requests.get(SIMPLIFY_URL, timeout=60)
    resp.raise_for_status()
    listings = resp.json()
    found, rejected = boards_from_listings(listings)
    seeds = read_boards(SEED_BOARDS)
    boards = list(dict.fromkeys(seeds + found))

    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    write_boards(
        boards,
        OUTPUT,
        header=f"Generated by jd_analyzer.discover at {stamp}\n"
        f"{len(seeds)} seeds from boards.txt + {len(found)} boards from {len(listings)} Simplify listings",
    )
    print(f"{len(listings)} Simplify listings -> {len(found)} unique boards")
    print(f"  by job board: {dict(Counter(b.source for b in found))}")
    print(f"  plus {len(seeds)} seeds from boards.txt = {len(boards)} total")
    if rejected:
        print(f"  skipped {len(rejected)} links with unsafe tokens, e.g. {rejected[:3]}")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
